"""MinIO integration checks against a disposable, explicitly configured bucket."""

import os
import re
from uuid import uuid4

import aioboto3
import pytest
import pytest_asyncio
from botocore.config import Config
from botocore.exceptions import ClientError

from crawler_content.settings import ContentSettings
from crawler_content.storage import ObjectNotFoundError, ObjectStorage, StorageSizeError

pytestmark = [pytest.mark.integration, pytest.mark.asyncio]


@pytest_asyncio.fixture
async def storage_bucket():
    endpoint = os.environ["CONTENT_TEST_S3_ENDPOINT"]
    access = os.environ["CONTENT_TEST_S3_ACCESS_KEY"]
    secret = os.environ["CONTENT_TEST_S3_SECRET_KEY"]
    bucket = "content-test-" + uuid4().hex
    config = Config(signature_version="s3v4", s3={"addressing_style": "path"}, retries={"total_max_attempts": 1})
    async with aioboto3.Session().client("s3", endpoint_url=endpoint, aws_access_key_id=access,
                                        aws_secret_access_key=secret, config=config) as client:
        await client.create_bucket(Bucket=bucket)
        try:
            yield client, bucket, endpoint, access, secret
        finally:
            if not re.fullmatch(r"content-test-[0-9a-f]{32}", bucket):
                raise RuntimeError("Refusing to delete a non-test bucket")
            # All keys are generated by this test; no other buckets are touched.
            listing = await client.list_objects_v2(Bucket=bucket)
            for item in listing.get("Contents", []):
                await client.delete_object(Bucket=bucket, Key=item["Key"])
            await client.delete_bucket(Bucket=bucket)


async def test_minio_read_limit_missing_and_bucket_isolation(storage_bucket):
    client, bucket, endpoint, access, secret = storage_bucket
    key = "crawls/test/fetches/1/" + uuid4().hex + ".html"
    await client.put_object(Bucket=bucket, Key=key, Body=b"<p>Hello</p>")
    settings = ContentSettings(
        database_url="postgresql+asyncpg://unused:unused@localhost/content_db", rabbitmq_url="amqp://localhost/",
        elasticsearch_url="http://localhost:9200", object_storage_endpoint=endpoint,
        object_storage_access_key=access, object_storage_secret_key=secret, object_storage_bucket=bucket,
        content_max_body_bytes=12,
    )
    async with ObjectStorage(settings) as storage:
        assert await storage.read(key) == b"<p>Hello</p>"
        with pytest.raises(ObjectNotFoundError):
            await storage.read("missing-" + uuid4().hex)
        await client.put_object(Bucket=bucket, Key=key, Body=b"x" * 13)
        with pytest.raises(StorageSizeError):
            await storage.read(key)
        # A bucket-shaped key still refers to this bucket.
        with pytest.raises(ObjectNotFoundError):
            await storage.read(f"other-bucket/{key}")
        # MinIO rejects the opaque URI-shaped key rather than switching buckets.
        with pytest.raises(ClientError) as caught:
            await storage.read(f"s3://other-bucket/{key}")
        assert caught.value.response["Error"]["Code"] == "XMinioInvalidObjectName"
